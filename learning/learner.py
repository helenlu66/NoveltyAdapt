    def _load_llm_reward_fn_candidates(self) -> List[Callable]:
        """Load the LLM generated reward shaping function candidates for the grounded operator

        Returns:
            List[Callable]: a list of reward shaping functions
        """
        op_name, _ = extract_name_params_from_grounded(self.grounded_operator.ident())
        reward_fn_candidates = []
        for i in range(self.config['learning']['reward_shaping_fn']['num_candidates']):
            try:
                llm_reward_shaping_func = load_llm_reward_shaping_fn_candidate(self.args.domain, op_name, i, self.args.rw_type)
                reward_fn_candidates.append(llm_reward_shaping_func)
            except:
                func = prompt_llm_for_reward_shaping_fn_candidate(self.grounded_operator, get_observation_with_semantics(self.unwrapped_env), self.args.rw_type)
                # save the output python function to a file in the reward_functions directory
                # create the directory if it does not exist
                if not os.path.exists(f"learning{os.sep}reward_functions{os.sep}{self.args.domain}"):
                    os.makedirs(f"learning{os.sep}reward_functions{os.sep}{self.args.domain}")
                # create a file with the operator's name and save the function in it
                with open(f"learning{os.sep}reward_functions{os.sep}{self.args.domain}{os.sep}{op_name}_{i}.py", 'w') as f:
                    f.write(func)
                # wait 5 seconds for the file to be saved
                time.sleep(5)
                llm_reward_func_module = importlib.import_module(f"learning.reward_functions.{self.args.domain}.{op_name}_{i}")
                llm_reward_shaping_func = getattr(llm_reward_func_module, 'reward_shaping_fn')
                reward_fn_candidates.append(llm_reward_shaping_func)
        return reward_fn_candidates
    
    def _filter_semantically_same_candidates(self, subgoal:fs.SingleEffect, candidates:List[LLMRewardShapingFnCandidate]) -> Dict[int, LLMRewardShapingFnCandidate]:
        """Filter out reward shaping function candidates that are semantically the same for the current subgoal

        Args:
            subgoal (fs.SingleEffect): the subgoal to check the candidates against
            candidates (List[LLMRewardShapingFnCandidate]): the list of reward shaping function candidates to filter

        Returns:
            Dict[int, LLMRewardShapingFnCandidate]: a dictionary of the filtered reward shaping function candidates, where the keys are the indices of the candidates in the original list and the values are the candidates themselves
        """
        candidate_idxs_to_remove = set()
        # for each pair of candidates, check whether they are semantically the same for the current subgoal. If they are, add the one with the higher index to the candidate_idxs_to_remove set
        for i in range(len(candidates)):
            for j in range(i + 1, len(candidates)):
                if check_subgoal_duplicate(subgoal=subgoal, candidate1=candidates[i], candidate2=candidates[j], env=self.unwrapped_env):
                    candidate_idxs_to_remove.add(j)
        # Remove the filtered candidates from the list
        filtered_candidates = {i: candidate for i, candidate in enumerate(candidates) if i not in candidate_idxs_to_remove}
        return filtered_candidates

